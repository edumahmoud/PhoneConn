// Build reverse lookup map once
const OUI_MAP: Map<string, string> = (() => {
  const m = new Map<string, string>();
  for (const [vendor, prefixes] of Object.entries(VENDORS)) {
    for (const p of prefixes) {
      if (!m.has(p)) m.set(p, vendor);
    }
  }
  return m;
})();

/** Normalize any MAC format to uppercase colon-separated (AA:BB:CC:...). */
export function normalizeMac(raw: string): string {
  const hex = raw.replace(/[^0-9a-fA-F]/g, "").toUpperCase();
  if (hex.length !== 12) return raw.trim().toUpperCase();
  return (hex.match(/.{2}/g) ?? [raw]).join(":");
}

/** Look up the vendor for a MAC address. Returns null when unknown. */
export function ouiVendor(mac: string): string | null {
  const norm = normalizeMac(mac);
  const prefix = norm.slice(0, 8);
  return OUI_MAP.get(prefix) ?? null;
}

/**
 * A "locally administered" MAC (2nd hex digit ∈ {2,6,A,E}) is usually a
 * randomized/privacy MAC from modern phones (iOS 14+, Android 10+).
 */
export function isRandomizedMac(mac: string): boolean {
  const norm = normalizeMac(mac);
  if (norm.length !== 17) return false;
  const digit = parseInt(norm[1], 16);
  if (Number.isNaN(digit)) return false;
  return (digit & 0b10) !== 0 && norm !== "FF:FF:FF:FF:FF:FF";
}

/** Multicast/broadcast MAC — never a real host. */
export function isMulticastMac(mac: string): boolean {
  const norm = normalizeMac(mac);
  if (norm.length !== 17) return false;
  const digit = parseInt(norm[1], 16);
  if (Number.isNaN(digit)) return false;
  return (digit & 0b1) !== 0;
}
